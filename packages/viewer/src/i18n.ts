export const messages = { zh, en };
export type Message = keyof typeof en;
export type Translate = (key: Message, n?: number) => string;
export const translate =
  (lang: Language): Translate =>
  (key, n) =>
    n === undefined
      ? messages[lang][key]
      : messages[lang][key].replace("{n}", String(n));
export const language = (
  requested: Language | undefined,
  browser: string,
): Language =>
  requested ?? (browser.toLowerCase().startsWith("zh") ? "zh" : "en");
